package com.rivell.workbench.platform.parsing;

import com.rivell.workbench.taxonomy.ConceptKey;

import java.io.ByteArrayInputStream;
import java.time.Instant;
import java.util.List;
import java.util.Map;
import java.util.UUID;

import org.docx4j.openpackaging.packages.WordprocessingMLPackage;

import com.rivell.workbench.contracts.ContractStructure;
import com.rivell.workbench.contracts.DocumentNode;
import com.rivell.workbench.contracts.DocumentNodeType;
import com.rivell.workbench.redline.ApprovedChangeSet;
import com.rivell.workbench.redline.DocumentExecutionPlan;
import com.rivell.workbench.redline.RedlinePlanResolver;
import com.rivell.workbench.redline.RedlineTestStructures;

/** Real-fixture pipeline helper: fixture bytes → M1 structure → resolved plan. */
public final class RedlineFixturePipeline {

    public static final String AUTHOR = "Rivell";
    public static final Instant EXECUTED_AT = Instant.parse("2026-09-26T10:00:00Z");
    public static final String SOURCE_SHA = "c".repeat(64);

    private RedlineFixturePipeline() {
    }

    public static byte[] fixture(String name) {
        try (var stream = RedlineFixturePipeline.class.getClassLoader()
                .getResourceAsStream("fixtures/" + name)) {
            if (stream == null) {
                throw new IllegalStateException("missing fixture " + name);
            }
            return stream.readAllBytes();
        } catch (Exception e) {
            throw new IllegalStateException("could not read fixture " + name, e);
        }
    }

    public static ContractStructure parse(String fixture, UUID contractId, UUID versionId) {
        var result = new DocxStructuralParser(new DocxParserProperties(200L * 1024 * 1024))
                .parse(new ByteArrayInputStream(fixture(fixture)), versionId);
        return new ContractStructure(contractId, 1, result.parserVersion(), result.status(),
                result.warnings(), result.nodes());
    }

    public static DocumentExecutionPlan plan(
            ContractStructure structure,
            ApprovedChangeSet set,
            Map<UUID, ConceptKey> effectivePrimaryConcepts) {
        return new RedlinePlanResolver().resolve(set, structure, effectivePrimaryConcepts,
                AUTHOR, EXECUTED_AT, SOURCE_SHA);
    }

    public static Map<UUID, ConceptKey> concepts(
            ContractStructure structure, Map<String, ConceptKey> byHeadingText) {
        return RedlineTestStructures.concepts(structure, byHeadingText);
    }

    public static UUID headingId(ContractStructure structure, String headingText) {
        return structure.nodes().stream()
                .filter(node -> node.nodeType() == DocumentNodeType.HEADING)
                .filter(node -> headingText.equals(node.text()))
                .map(DocumentNode::id)
                .findFirst()
                .orElseThrow();
    }

    public static List<String> headingTexts(ContractStructure structure) {
        return structure.nodes().stream()
                .filter(node -> node.nodeType() == DocumentNodeType.HEADING)
                .map(DocumentNode::text)
                .toList();
    }

    public static WordprocessingMLPackage load(byte[] bytes) {
        try {
            return WordprocessingMLPackage.load(new ByteArrayInputStream(bytes));
        } catch (Exception e) {
            throw new IllegalStateException("could not load generated bytes", e);
        }
    }

    public static String xml(Object element) {
        return org.docx4j.XmlUtils.marshaltoString(element, true, true);
    }
}
